    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed


            Estado estado = obterEstadoDaTela();

            boolean salvou = controleEstado.inserirEstado(estado);
            if (salvou) {

                JOptionPane.showMessageDialog(this, "Estado salvo com sucesso!");

                // Mostra imediatamente o último cadastro
                mostrarEstado(controleEstado.ultimo());

                atualizarBotoes();
            }

       

    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
         Estado estado = obterEstadoDaTela();

            if (controleEstado.alterarEstado(estado)) {

                JOptionPane.showMessageDialog(this, "Estado alterado com sucesso!");

                mostrarEstado(estado);

                atualizarBotoes();
            }

    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int id = Integer.parseInt(txtId.getText());

        Estado estado = controleEstado.getEstadoPorId(id);

        if (estado == null) {

            JOptionPane.showMessageDialog(this, "Estado não encontrado.");

            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir o estado?", "Confirmação", JOptionPane.YES_NO_OPTION);

        if (resposta == JOptionPane.YES_OPTION) {

            Estado proximoEstado = controleEstado.deletarEstado(id);

            JOptionPane.showMessageDialog(this, "Estado excluído com sucesso!");

            if (proximoEstado == null) {

                // Não existem mais estados
                limparCampos();

                atualizarBotoes();

                JOptionPane.showMessageDialog(this, "Não existem mais estados cadastrados.");

            } else {

                // Mostra o próximo ou o anterior
                mostrarEstado(proximoEstado);
                atualizarBotoes();
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed


