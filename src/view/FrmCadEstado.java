private void mostrarEstado(Estado estado) {

        if (estado == null) {
            return;
        }

        txtId.setText(String.valueOf(estado.getId()));
        txtNome.setText(estado.getNome());
        txtSigla.setText(estado.getSigla());
        
    }

    public void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtSigla.setText("");
        
    }

    private void atualizarBotoes() {

        if (!controleEstado.temEstados()) {

            btnPrimeiro.setEnabled(false);
            btnAnterior.setEnabled(false);
            btnProximo.setEnabled(false);
            btnUltimo.setEnabled(false);

            return;
        }

        btnPrimeiro.setEnabled(true);
        btnUltimo.setEnabled(true);

        btnAnterior.setEnabled(controleEstado.temAnterior());

        btnProximo.setEnabled(controleEstado.temProximo());
    }

    private Estado obterEstadoDaTela() {

        Estado estado = new Estado();

        if (!txtId.getText().isEmpty()) {
            estado.setId(Integer.parseInt(txtId.getText()));
        }

        estado.setNome(txtNome.getText());
        estado.setSigla(txtSigla.getText());
        

        return estado;
    }


